import { readFile, writeFile } from 'node:fs/promises'
import { pathToFileURL } from 'node:url'

async function loadEsbuild() {
  if (process.env.DSH_HOST_ESBUILD_PATH) {
    try { return await import(pathToFileURL(process.env.DSH_HOST_ESBUILD_PATH).href) } catch {}
  }
  try { return await import('esbuild') } catch {}
  return null
}

const icons = {}
for (const [id, filename, mime] of [['codex', 'codex.png', 'image/png'], ['claude-code', 'claude-code.svg', 'image/svg+xml'], ['antigravity', 'antigravity.svg', 'image/svg+xml'], ['deepseek-harness', 'deepseek-harness.svg', 'image/svg+xml']]) {
  icons[id] = `data:${mime};base64,${(await readFile(new URL(`./assets/${filename}`, import.meta.url))).toString('base64')}`
}
const iconSource = `export const AGENT_ICONS = ${JSON.stringify(icons)}\n`
await writeFile(new URL('./icons.mjs', import.meta.url), iconSource)
const contract = (await readFile(new URL('./remote-contract.mjs', import.meta.url), 'utf8')).replace(/^export /gm, '')
const consoleModules = await Promise.all(['console-contract.mjs', 'console-client.mjs', 'preset-view.mjs', 'native-ui-projections.mjs', 'native-context.mjs', 'native-host-format.mjs', 'delegation-mentions.mjs', 'delegation-client.mjs', 'permission-presentation.mjs', 'slider-runtime.mjs', 'native-model-runtime.mjs', 'native-replies-client.mjs', 'native-compaction-client.mjs', 'file-uri-links.mjs', 'native-turn-usage-client.mjs', 'native-live-status-client.mjs'].map(async name =>
  (await readFile(new URL(name, import.meta.url), 'utf8')).replace(/^import .*\r?\n/gm, '').replace(/^export /gm, '')))
consoleModules[0] = `const {consoleRemoteContribution}=(()=>{${consoleModules[0]}\nreturn {consoleRemoteContribution};})();`
let client = await readFile(new URL('./client.mjs', import.meta.url), 'utf8')
const imports = client.match(/^import .*$/gm) ?? []
if (imports.length !== 19) throw new Error('Update the explicit client build when its imports change')
client = client.replace(/^import .*\r?\n/gm, '').replace(/^export /gm, '')
const pkg = JSON.parse(await readFile(new URL('./package.json', import.meta.url), 'utf8'))
const packageId = pkg.name || 'dsh-host'
let body = `window.__ModuleLoader__.load({id:${JSON.stringify(packageId)},factory:require=>{\nconst React=require("react"),ReactDOM=require("react-dom"),UiPrimitives=require("@deepseek-ai/dsh-client-ui-primitives");\nconst {createElement:h,useEffect,useRef,useState,useSyncExternalStore}=React;\nconst {createPortal}=ReactDOM;\nconst {Button:DshConsoleButton,Menu,RiskConfirmation,IconDatabaseOutlineRegular,IconChevronDownOutlineRegular,PermissionIconReadOnlyRegular,PermissionIconWorkspaceWriteRegular,PermissionIconFullAccessRegular}=UiPrimitives;\nconst AGENT_ICONS=${JSON.stringify(icons)};\n${contract}\n${consoleModules.join('\n')}\n${client}\nconst exports={inject,apply};Object.defineProperty(exports,Symbol.toStringTag,{value:"Module"});return exports;\n}});\n`
const esbuild = await loadEsbuild()
if (esbuild?.transform) {
  body = (await esbuild.transform(body, { loader: 'js', target: 'es2022', minify: true, legalComments: 'none' })).code
}
const output = `// Generated by build-client.mjs. Edit client.mjs and run npm run build:client.\n${body}`
await writeFile(new URL('./client.js', import.meta.url), output)
